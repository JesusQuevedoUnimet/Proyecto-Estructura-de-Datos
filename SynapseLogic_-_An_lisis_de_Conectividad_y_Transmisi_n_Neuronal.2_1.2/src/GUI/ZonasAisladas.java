    /**
     * MÉTODO AUXILIAR: Llena el ComboBox con los IDs de las neuronas reales de tu Grafo
     */
    private void cargarComboNeuronas() {
        if (this.grafo == null) return;
        cbOrigen.removeAllItems();
        Estructuras.ListaPropia<Modelo.Neurona> lista = grafo.getNeuronas();
        for (int i = 0; i < lista.getTamaño(); i++) {
            cbOrigen.addItem(lista.obtener(i).getId());
        }
    }

    /**
     * MÉTODO AUXILIAR: Lógica que se ejecuta al darle al botón Analizar
     */
    private void ejecutarAnalisis() {
        if (this.grafo == null || cbOrigen.getSelectedItem() == null) return;
        
        String idInicio = cbOrigen.getSelectedItem().toString();
        String algoritmo = cbAlgoritmo.getSelectedItem().toString();
        String resultadoRecorrido = "";
        
        // 1. Ejecuta el algoritmo seleccionado (BFS o DFS) usando los métodos de tu clase Grafo
        if (algoritmo.contains("BFS")) {
            resultadoRecorrido = grafo.BFS(idInicio);
        } else {
            resultadoRecorrido = grafo.DFS(idInicio);
        }
        
        // Muestra el camino recorrido en el JTextArea superior (el grande)
        jTextArea1.setText(resultadoRecorrido);
        
        // 2. Busca las zonas aisladas usando el método que leímos en tu Grafo
        String resultadoAisladas = grafo.obtenerZonasAisladas();
        
        // Muestra las neuronas desconectadas en el JTextArea de la derecha
        jTextArea2.setText(resultadoAisladas);
    }

