    /**
     * Método auxiliar para refrescar la Lista y el ComboBox usando tus estructuras
     */
    private void actualizarComponentes() {
        modeloLista.clear();
        cbEliminarID.removeAllItems();
        
        // Recorremos tu ListaPropia de neuronas usando los métodos getTamaño() y obtener(i)
        Estructuras.ListaPropia<Neurona> listaNeuronas = grafo.getNeuronas();
        for (int i = 0; i < listaNeuronas.getTamaño(); i++) {
            // ¡CORREGIDO!: Cambiado 'obtain' por el método real de tu clase: 'obtener'
            Neurona n = listaNeuronas.obtener(i); 
            
            if (n != null) {
                modeloLista.addElement(n.getId());
                cbEliminarID.addItem(n.getId());
            }
        }
    }

