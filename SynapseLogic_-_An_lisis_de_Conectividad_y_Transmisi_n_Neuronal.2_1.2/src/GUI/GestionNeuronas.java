    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
String nuevoID = textNuevoID.getText().trim();
        
        if (nuevoID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El ID de la neurona no puede estar vacío.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if (grafo.buscarNeurona(nuevoID) != null) { 
            JOptionPane.showMessageDialog(this, "Esta neurona ya existe en el sistema.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        grafo.agregarNeurona(nuevoID); 
        
        JOptionPane.showMessageDialog(this, "Neurona '" + nuevoID + "' agregada con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        textNuevoID.setText(""); 
        actualizarComponentes();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
String idAEliminar = (String) cbEliminarID.getSelectedItem();
        
        if (idAEliminar == null) {
            JOptionPane.showMessageDialog(this, "No hay ninguna neurona seleccionada para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int confirmacion = JOptionPane.showConfirmDialog(this, 
                "¿Estás seguro de eliminar la neurona '" + idAEliminar + "'? Se borrarán también sus sinapsis conectadas.", 
                "Confirmar Eliminación", JOptionPane.YES_NO_OPTION);
                
        if (confirmacion == JOptionPane.YES_OPTION) {
            grafo.eliminarNeurona(idAEliminar); 
            
            JOptionPane.showMessageDialog(this, "Neurona ejecutada correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            actualizarComponentes(); 
        }    }//GEN-LAST:event_btnEliminarActionPerformed

