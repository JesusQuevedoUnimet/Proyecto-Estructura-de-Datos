/**
     * MÉTODO AUXILIAR: Ejecuta la lógica de Dijkstra al presionar el botón
     */
    private void ejecutarDijkstra() {
        if (this.grafo == null || cbDijkstraOrigen.getSelectedItem() == null || cbDijkstraDestino.getSelectedItem() == null) {
            return;
        }
        
        String origen = cbDijkstraOrigen.getSelectedItem().toString();
        String destino = cbDijkstraDestino.getSelectedItem().toString();
        
        // Si eligen la misma neurona, no hace falta calcular nada
        if (origen.equals(destino)) {
            IblResultadoRuta.setText("Ruta: " + origen);
            IblTiempoTotal.setText("Tiempo Total: 0.0 ms");
            return;
        }
        
        // Ejecutamos tu método dijkstra pasándole el origen
        String resultadoCamino = grafo.dijkstra(origen); 
        
        // Mostramos el resultado de los caminos en tu etiqueta de texto
        IblResultadoRuta.setText("Ruta: " + resultadoCamino);
        IblTiempoTotal.setText("Caminos optimizados desde " + origen + " con éxito.");
    }

