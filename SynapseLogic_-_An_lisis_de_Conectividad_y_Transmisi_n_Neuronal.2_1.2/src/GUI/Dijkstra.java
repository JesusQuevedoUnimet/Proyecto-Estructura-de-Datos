    /**
     * MÉTODO AUXILIAR: Llena ambos ComboBoxes dinámicamente con los IDs de tus neuronas reales
     */
    private void cargarComboNeuronas() {
        if (this.grafo == null) return;
        
        // Limpiamos los elementos de prueba que pone NetBeans
        cbDijkstraOrigen.removeAllItems();
        cbDijkstraDestino.removeAllItems();
        
        // Obtenemos la lista de neuronas de tu clase Grafo
        Estructuras.ListaPropia<Modelo.Neurona> lista = grafo.getNeuronas();
        for (int i = 0; i < lista.getTamaño(); i++) {
            String id = lista.obtener(i).getId();
            cbDijkstraOrigen.addItem(id);
            cbDijkstraDestino.addItem(id);
        }
    }

